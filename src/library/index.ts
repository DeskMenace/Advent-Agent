/** Idea library loader and index builder (GIFT_WORKSHOP.md §4, D2). Deterministic: no timestamps. */
import { readdirSync, readFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { IDEA_GROUPS, IDEA_GROUP_NAMES, IdeaFrontmatterSchema, type IdeaFrontmatter, type IdeaIndexEntry } from '../shared/idea.js';
import { parseFrontmatter } from './frontmatter.js';

export const INDEX_SCHEMA = 'advent-agent/idea-index@1';

export interface LoadedIdea {
  /** Path relative to the library root, e.g. `ideas/annual-roast.md`. */
  file: string;
  frontmatter: IdeaFrontmatter;
  body: string;
}

export interface IdeaIndex {
  schema: typeof INDEX_SCHEMA;
  count: number;
  groups: Record<(typeof IDEA_GROUPS)[number], string>;
  ideas: IdeaIndexEntry[];
}

/** Parses one idea file. Throws an Error that names the file on any parse or schema failure. */
export function loadIdeaFile(path: string, file: string): LoadedIdea {
  let parsed;
  try {
    parsed = parseFrontmatter(readFileSync(path, 'utf8'));
  } catch (err) {
    throw new Error(`${file}: ${(err as Error).message}`);
  }
  const result = IdeaFrontmatterSchema.safeParse(parsed.data);
  if (!result.success) {
    const issues = result.error.issues.map((i) => `  ${i.path.join('.') || '(root)'}: ${i.message}`).join('\n');
    throw new Error(`${file}: invalid idea frontmatter\n${issues}`);
  }
  const expectedId = basename(file, '.md');
  if (result.data.id !== expectedId) throw new Error(`${file}: id "${result.data.id}" does not match the file name "${expectedId}"`);
  return { file, frontmatter: result.data, body: parsed.body };
}

/** Loads every `ideas/*.md` under the library root, sorted by file name. */
export function loadIdeas(dir: string): LoadedIdea[] {
  const ideasDir = join(dir, 'ideas');
  const files = readdirSync(ideasDir)
    .filter((f) => f.endsWith('.md'))
    .sort();
  const ideas = files.map((f) => loadIdeaFile(join(ideasDir, f), `ideas/${f}`));
  const seen = new Map<string, string>();
  for (const idea of ideas) {
    const dup = seen.get(idea.frontmatter.id);
    if (dup) throw new Error(`${idea.file}: duplicate id "${idea.frontmatter.id}" (also in ${dup})`);
    seen.set(idea.frontmatter.id, idea.file);
  }
  return ideas;
}

const compare = (a: string, b: string): number => a.localeCompare(b, 'en');

export function buildIndex(ideas: LoadedIdea[]): IdeaIndex {
  const entries: IdeaIndexEntry[] = ideas.map(({ file, frontmatter: f }) => ({
    id: f.id,
    title: f.title,
    group: f.group,
    summary: f.summary,
    suitable_if: f.suitable_if,
    skills: f.skills,
    effort: f.effort,
    real_world: f.real_world,
    status: f.status,
    file,
  }));
  entries.sort((a, b) => compare(a.group, b.group) || compare(a.title, b.title) || compare(a.id, b.id));
  return { schema: INDEX_SCHEMA, count: entries.length, groups: { ...IDEA_GROUP_NAMES }, ideas: entries };
}

export function renderIndexJson(index: IdeaIndex): string {
  return JSON.stringify(index, null, 2) + '\n';
}

const cell = (s: string): string => s.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

export function renderIndexMarkdown(index: IdeaIndex): string {
  const out: string[] = [
    '# Gift idea index',
    '',
    `Generated by \`npm run library:index\` from \`gift-library/ideas/*.md\`. Do not edit by hand. ${index.count} ideas.`,
    '',
    'Ideas are inspiration, never a quota: the agent chooses and makes the gift and may ignore this list. Real-world ideas are proposals; the recipient buys or books.',
    '',
  ];
  for (const group of IDEA_GROUPS) {
    const rows = index.ideas.filter((i) => i.group === group);
    out.push(`## ${group}. ${index.groups[group]}`, '');
    if (rows.length === 0) {
      out.push('_No ideas yet._', '');
      continue;
    }
    out.push('| id | title | summary | suitable_if | status |', '|---|---|---|---|---|');
    for (const r of rows) out.push(`| [${r.id}](${r.file}) | ${cell(r.title)} | ${cell(r.summary)} | ${cell(r.suitable_if)} | ${r.status} |`);
    out.push('');
  }
  return out.join('\n');
}
